#!/usr/bin/env python3
"""Score the manual review of the defect table.

data/defects_table_reviewed.csv is data/defects_table.csv with the
`your_verdict` column filled in for every (repository, rule) pair by a
reviewer who checked each pair at its pinned commit ("yes defect: ..." or
"no defect: ..." with a one-line reason). This script joins it to the
current data/defects_table.csv on (repo, rule) and reports raw agreement
and Cohen's kappa against the study's decision (counted_as_defect), overall,
on the pairs the adjudicator ruled on, on the pairs where scanner and audit
agreed, and per rule. Output: data/second_reader_score.json and
paper/second_reader.tex.
"""
from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
PAPER = DATA.parent / "paper"


def kappa(pairs: list[tuple[str, str]]) -> tuple[float, float]:
    n = len(pairs)
    if not n:
        return 0.0, 0.0
    agree = sum(a == b for a, b in pairs) / n
    pa = sum(a == "defect" for a, _ in pairs) / n
    pb = sum(b == "defect" for _, b in pairs) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    return agree, (agree - pe) / (1 - pe) if pe < 1 else 1.0


def main() -> None:
    reader = {}
    for r in csv.DictReader((DATA / "defects_table_reviewed.csv").open(newline="", encoding="utf-8-sig")):
        text = (r.get("your_verdict") or "").strip()
        if not text:
            continue
        low = text.lower()
        verdict = "defect" if low.startswith(("yes", "defect")) else "not_defect"
        label, _, note = text.partition(":")
        reader[(r["repo"], r["rule"])] = {"verdict": verdict, "label": label.strip(), "note": note.strip()}
    table = list(csv.DictReader((DATA / "defects_table.csv").open(newline="")))
    joined = []
    for r in table:
        s = reader.get((r["repo"], r["rule"]))
        if s is None:
            continue
        ours = "defect" if r["counted_as_defect"] == "yes" else "not_defect"
        joined.append((r["rule"], r["audit_result"].startswith("disagreement"), ours, s["verdict"], s["label"]))
    res: dict = {"n_reader": len(reader), "n_table": len(table), "n_joined": len(joined)}
    spec_rules = {"frontmatter/format-valid", "frontmatter/description-required"}
    for key, sel in (("all", lambda r, d: True), ("adjudicated", lambda r, d: d), ("agreed", lambda r, d: not d),
                     ("excluding_spec", lambda r, d: r not in spec_rules)):
        pairs = [(o, t) for r, d, o, t, _ in joined if sel(r, d)]
        a, k = kappa(pairs)
        res[key] = {"n": len(pairs), "agreement": round(a, 4), "kappa": round(k, 4),
                    "reader_defect": sum(t == "defect" for _, t in pairs), "ours_defect": sum(o == "defect" for o, _ in pairs)}
    by_rule: dict = defaultdict(list)
    for rule, _, o, t, _ in joined:
        by_rule[rule].append((o, t))
    res["per_rule"] = {rule: {"n": len(p), "agreement": round(kappa(p)[0], 4),
                              "reader_defect": sum(t == "defect" for _, t in p), "ours_defect": sum(o == "defect" for o, _ in p)}
                       for rule, p in sorted(by_rule.items())}
    summ = json.loads((DATA / "summary.json").read_text())
    gp = set(summ["gating_rules"]) | set(summ["provisional_rules"])
    ga = [(o, t) for r, d, o, t, _ in joined if d and r in gp]
    res["gating_adjudicated"] = {"n": len(ga), "agree": sum(o == t for o, t in ga),
                                 "review_defect_study_not": sum(1 for o, t in ga if t == "defect" and o != "defect"),
                                 "review_not_study_defect": sum(1 for o, t in ga if t != "defect" and o == "defect")}
    res["labels"] = dict(sorted(((lab, sum(1 for j in joined if j[4] == lab)) for lab in {j[4] for j in joined}), key=lambda x: -x[1]))
    (DATA / "second_reader_score.json").write_text(json.dumps(res, indent=1))
    lines = ["% Generated by scripts/second_reader.py\n"]
    for key, K in (("all", "Sr"), ("adjudicated", "SrAdj"), ("agreed", "SrAgr"), ("excluding_spec", "SrX")):
        lines.append(f"\\newcommand{{\\n{K}}}{{{res[key]['n']:,}}}\n")
        lines.append(f"\\newcommand{{\\{K}Agree}}{{{100 * res[key]['agreement']:.1f}}}\n")
        lines.append(f"\\newcommand{{\\{K}Kappa}}{{{res[key]['kappa']:.2f}}}\n")
        lines.append(f"\\newcommand{{\\{K}ReaderDefect}}{{{res[key]['reader_defect']:,}}}\n")
        lines.append(f"\\newcommand{{\\{K}OursDefect}}{{{res[key]['ours_defect']:,}}}\n")
    g = res["gating_adjudicated"]
    lines.append(f"\\newcommand{{\\nSrGatingAdj}}{{{g['n']}}}\n")
    lines.append(f"\\newcommand{{\\SrGatingAdjAgree}}{{{g['agree']} of {g['n']}}}\n")
    lines.append(f"\\newcommand{{\\SrGatingAdjRevDefect}}{{{g['review_defect_study_not']}}}\n")
    lines.append(f"\\newcommand{{\\SrGatingAdjRevNot}}{{{g['review_not_study_defect']}}}\n")
    (PAPER / "second_reader.tex").write_text("".join(lines))
    print(json.dumps({k: v for k, v in res.items() if k != "per_rule"}, indent=1))
    for rule, v in res["per_rule"].items():
        print(f"  {rule:40s} n={v['n']:3d} agree={v['agreement']:.2f} reader={v['reader_defect']} ours={v['ours_defect']}")


if __name__ == "__main__":
    main()
