#!/usr/bin/env python3
"""Produce paper/main_standalone.tex: main.tex with every \\input{...} replaced
by the file's contents, so the paper is one .tex plus results.png. Run after
analyze.py; the generated tables and numbers are inlined at their current
values, so re-run this whenever the numbers change."""
from __future__ import annotations

import re
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent / "paper"
src = (PAPER / "main.tex").read_text()


def _inline(m: re.Match[str]) -> str:
    name = m.group(1)
    p = PAPER / (name if name.endswith(".tex") else name + ".tex")
    body = p.read_text().rstrip("\n")
    # The comment lines must be complete lines: a `}` that follows the
    # \input on the same line (resizebox) would otherwise be commented out.
    return f"%% ---- begin inlined {p.name} (generated by scripts/analyze.py) ----\n{body}\n%% ---- end inlined {p.name} ----\n"


# Macro files (numbers, reachability, scope counts) are not inlined as
# \newcommand blocks; every macro use in the body is replaced by its value,
# so the standalone reads as ordinary prose. Table files are inlined.
MACRO_FILES = ("numbers.tex", "reachability.tex", "table_scope_counts.tex", "second_reader.tex")
macros: dict[str, str] = {}
for name in MACRO_FILES:
    for m in re.finditer(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", (PAPER / name).read_text(), flags=re.M):
        macros[m.group(1)] = m.group(2)


def _expand(text: str) -> str:
    # Longest names first so \SetupConfSecLo is not clipped to \SetupConfSec.
    for name in sorted(macros, key=len, reverse=True):
        # a callable replacement is inserted literally: no backslash escaping
        text = re.sub(r"\\" + name + r"(?:\{\})?(?![A-Za-z])", lambda _m, v=macros[name]: v, text)
    return text


src = re.sub(r"^\\input\{(numbers|reachability|table_scope_counts|second_reader)\}\s*$", "", src, flags=re.M)
out = re.sub(r"\\input\{([^}]+)\}", _inline, src)
out = _expand(out)
leftover = sorted(set(re.findall(r"\\((?:Setup|Coll|Instr|Asm|Aud|Reach|Chan|Grant|n[A-Z]|scope)[A-Za-z]*)", out)))
assert not leftover, f"unexpanded macros: {leftover}"
out = out.replace("\\includegraphics[width=0.70\\textwidth]{figures/results}", "\\includegraphics[width=0.70\\textwidth]{results.png}")
out = out.replace(
    "%% Every number in this file is a macro defined in numbers.tex, which",
    "%% STANDALONE BUILD: numbers.tex and the generated tables are inlined below.\n"
    "%% Only results.png must sit next to this file. Regenerate with\n"
    "%% `make analyze && make standalone`; do not edit the inlined blocks by hand.\n"
    "%% Every number in this file is a macro defined in numbers.tex, which",
)
assert "\\input{" not in out, "unresolved \\input remains"

# Guard: the figure must have been drawn from the same numbers as the macros.
import json
vals = json.loads((PAPER.parent / "figures" / "results_values.json").read_text())
numbers = (PAPER / "numbers.tex").read_text()
def macro(name):
    m = re.search(r"\\newcommand\{\\" + name + r"\}\{([^}]*)\}", numbers)
    return float(m.group(1).replace(",", "")) if m else None
for st, key in (("SETUP", "SetupConfirmedDefect"), ("COLLECTION", "CollConfirmedDefect"), ("INSTRUCTION_ONLY", "InstrConfirmed")):
    if st in vals["left"] and abs(vals["left"][st] - macro(key)) > 0.05:
        raise SystemExit(f"STALE FIGURE: figure shows {vals['left'][st]} for {st}, numbers.tex says {macro(key)}. Run analyze.py.")
(PAPER / "main_standalone.tex").write_text(out)
print(f"wrote paper/main_standalone.tex ({len(out.splitlines())} lines)")
